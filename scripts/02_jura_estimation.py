"""Jura estimation: softmax GPC versus three simple-IK variants.

Kernel families are chosen per method: the GPC latent kernel by Laplace
evidence (Matern 3/2 over exponential), and the indicator covariance as the
exponential model, the usual choice for indicators, whose covariances are
linear at the origin. GPC probabilities are the plug-in softmax of the
latent predictive mean, the predictor that Sect. 4 linearizes; the Monte
Carlo predictive average is reported alongside.

Produces Table 1 (order-relation diagnostics on raw estimates), Figs. 2-3
(probability, hard-class and confidence maps) and the run times quoted in
Sect. 6. Grid predictions are cached for scripts 03 and 05.
"""
import json
import sys
import time
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.colors import ListedColormap, BoundaryNorm
from scipy.spatial import ConvexHull

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from ikgpc import IndicatorKriging, Matern12, Matern32, SoftmaxGPC, metrics  # noqa: E402
from ikgpc.jura import ROCK_NAMES, hull_mask, load_jura, make_grid  # noqa: E402
from ikgpc.plotting import CLASS_COLORS, save, setup  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
TAB = ROOT / "results" / "tables"
CACHE = ROOT / "results" / "jura_grid_predictions.npz"


def kernel_dict(k, nugget=None):
    d = {"variance": float(k.variance), "lengthscales_km": [float(v) for v in k.lengthscales]}
    if nugget is not None:
        d["nugget"] = float(nugget)
    return d


def main():
    setup()
    TAB.mkdir(parents=True, exist_ok=True)
    X, z = load_jura()
    C = 5
    GX, GY, Xg = make_grid(X, n=80)
    inside = hull_mask(X, Xg)
    timings = {}

    gpc = SoftmaxGPC(Matern32(variance=4.0, lengthscales=(0.5,)), optimize="isotropic").fit(X, z, C)
    timings.update({f"gpc_{k}": v for k, v in gpc.timings.items()})
    timings["gpc_lml_evaluations"] = gpc.n_lml_evals_
    t0 = time.perf_counter(); f_mean, f_cov = gpc.predict_latent(Xg)
    timings["gpc_predict_latent_s"] = time.perf_counter() - t0
    t0 = time.perf_counter(); P_mc = gpc.predict_proba(Xg, method="mc", n_samples=2000)
    timings["gpc_predict_proba_mc2000_s"] = time.perf_counter() - t0
    P_gpc = gpc.predict_proba(Xg, method="plugin")

    # kernel-family check: exponential latent kernel for GPC, Matern 3/2 for IK
    gpc_exp = SoftmaxGPC(Matern12(variance=4.0, lengthscales=(0.5,)), optimize="isotropic").fit(X, z, C)
    ik_m32 = IndicatorKriging(Matern32(), shared=True, means="uniform").fit(X, z, C)
    ik_exp = IndicatorKriging(Matern12(), shared=True, means="uniform").fit(X, z, C)
    def ik_nll(ik):
        k, nug = ik.kernels_[0]
        return float(ik._neg_loglik(np.log([k.variance, k.lengthscales[0], nug]), ik.Y_ - ik.m_[:, None]))
    family = {"gpc_log_evidence_matern32": gpc.state_.log_q,
              "gpc_log_evidence_exponential": gpc_exp.state_.log_q,
              "ik_neg_loglik_matern32": ik_nll(ik_m32), "ik_neg_loglik_exponential": ik_nll(ik_exp)}

    variants = {
        "IK, shared kernel, mean 1/C": IndicatorKriging(Matern12(), shared=True, means="uniform"),
        "IK, shared kernel, class proportions": IndicatorKriging(Matern12(), shared=True, means="proportions"),
        "IK, per-class kernels, class proportions": IndicatorKriging(Matern12(), shared=False, means="proportions"),
    }
    P_ik, rows, kernels = {}, [], {}
    for name, ik in variants.items():
        ik.fit(X, z, C)
        P_ik[name] = ik.predict(Xg)
        timings[f"{name} fit_s"] = ik.timings["fit_s"]
        timings[f"{name} predict_s"] = ik.timings["predict_s"]
        kernels[name] = [kernel_dict(k, nug) for k, nug in
                         (ik.kernels_[:1] if ik.shared else ik.kernels_)]
        row = {"method": name, **metrics.summarize(P_ik[name][inside])}
        row["closure_violation_after_clip_pct"] = 100 * float(
            np.mean(metrics.closure_deviation(np.clip(P_ik[name][inside], 0, 1)) > 0.01))
        rows.append(row)
    rows.append({"method": "Softmax GPC, plug-in", **metrics.summarize(P_gpc[inside]),
                 "closure_violation_after_clip_pct": 0.0})
    rows.append({"method": "Softmax GPC, predictive average", **metrics.summarize(P_mc[inside]),
                 "closure_violation_after_clip_pct": 0.0})
    kernels["Softmax GPC (Laplace)"] = [kernel_dict(gpc.kernel)]

    # ---- tables -----------------------------------------------------------
    import pandas as pd
    df = pd.DataFrame(rows)
    df.to_csv(TAB / "table1_order_relations.csv", index=False)
    print(df.to_string(index=False))
    with open(TAB / "table1_order_relations.tex", "w") as fh:
        fh.write("% generated by scripts/02_jura_estimation.py\n")
        for r in rows:
            fh.write(f"{r['method']} & {r['range_violation_pct']:.1f} & {r['range_excursion_gt_0.01_pct']:.1f} "
                     f"& {r['max_excursion']:.3f} & {r['closure_violation_pct']:.1f} & {r['max_closure_deviation']:.1e} \\\\\n")
    summary = {
        "n_data": int(len(z)), "n_grid": int(Xg.shape[0]), "n_grid_inside_hull": int(inside.sum()),
        "class_counts": np.bincount(z, minlength=C).tolist(),
        "gpc_log_marginal_likelihood": gpc.state_.log_q,
        "gpc_newton_iterations_final": gpc.state_.n_iter,
        "max_abs_sum_of_latent_means": float(np.abs(f_mean.sum(axis=1)).max()),
        "kernels": kernels, "kernel_family_check": family, "timings_s": timings,
    }
    (TAB / "jura_estimation_summary.json").write_text(json.dumps(summary, indent=2))
    np.savez_compressed(CACHE, Xg=Xg, GX=GX, GY=GY, inside=inside, P_gpc=P_gpc, P_mc=P_mc, f_mean=f_mean,
                        f_var=np.diagonal(f_cov, axis1=1, axis2=2),
                        **{f"P_ik{i}": P for i, P in enumerate(P_ik.values())})

    # ---- Fig. 2: probability maps ----------------------------------------
    P_A = P_ik["IK, shared kernel, mean 1/C"]
    hull = ConvexHull(X)
    hv = np.r_[hull.vertices, hull.vertices[0]]
    cmap = plt.get_cmap("RdYlBu_r")
    letters = "abcdefghij"
    fig, axes = plt.subplots(2, C, figsize=(7.7, 3.6), sharex=True, sharey=True, constrained_layout=True)
    for r, (P, lab) in enumerate([(P_A, "IK"), (P_gpc, "GPC (Laplace)")]):
        for c in range(C):
            ax = axes[r, c]
            Z = np.where(inside, P[:, c], np.nan).reshape(GX.shape)
            im = ax.pcolormesh(GX, GY, Z, cmap=cmap, vmin=0, vmax=1, shading="auto", rasterized=True)
            ax.plot(X[hv, 0], X[hv, 1], "k-", lw=0.8)
            other = z != c
            ax.scatter(X[other, 0], X[other, 1], s=3, facecolors="none", edgecolors="0.55", linewidths=0.3)
            ax.scatter(X[~other, 0], X[~other, 1], s=6, c="red", edgecolors="k", linewidths=0.25, zorder=3)
            ax.set_title(f"({letters[r * C + c]}) {lab}\nP({ROCK_NAMES[c]})", fontsize=8)
            ax.set_aspect("equal")
            ax.tick_params(labelsize=7.5)
            if c == 0:
                ax.set_ylabel("Y (km)", fontsize=8.5)
            if r == 1:
                ax.set_xlabel("X (km)", fontsize=8.5)
    cb = fig.colorbar(im, ax=axes, shrink=0.8, pad=0.01)
    cb.set_label("Probability", fontsize=8.5)
    cb.ax.tick_params(labelsize=7.5)
    save(fig, "figure2")

    # ---- Fig. 3: hard class and confidence -------------------------------
    cls_cmap = ListedColormap(CLASS_COLORS); cls_norm = BoundaryNorm(np.arange(-0.5, C), C)
    conf_cmap = plt.get_cmap("viridis").copy(); conf_cmap.set_over("#B2182B"); conf_cmap.set_bad("white")
    fig, axes = plt.subplots(2, 2, figsize=(4.75, 4.7), constrained_layout=True)
    for j, (P, lab) in enumerate([(P_A, "IK"), (P_gpc, "GPC")]):
        hard = np.where(inside, P.argmax(axis=1), np.nan).reshape(GX.shape)
        conf = np.where(inside, P.max(axis=1), np.nan).reshape(GX.shape)
        ax = axes[0, j]
        imc = ax.pcolormesh(GX, GY, hard, cmap=cls_cmap, norm=cls_norm, shading="auto", rasterized=True)
        ax.scatter(X[:, 0], X[:, 1], s=4, c=[CLASS_COLORS[k] for k in z], edgecolors="k", linewidths=0.25)
        ax.set_title(f"({'ab'[j]}) {lab}: most probable class", loc="left", fontsize=8)
        ax = axes[1, j]
        imf = ax.pcolormesh(GX, GY, conf, cmap=conf_cmap, vmin=0.2, vmax=1.01, shading="auto", rasterized=True)
        ax.scatter(X[:, 0], X[:, 1], s=1.2, c="w", lw=0)
        ax.set_title(f"({'cd'[j]}) {lab}: highest class probability", loc="left", fontsize=8)
        for ax in axes[:, j]:
            ax.set_aspect("equal"); ax.set_xlabel("Easting (km)")
        axes[0, j].set_ylabel("Northing (km)"); axes[1, j].set_ylabel("Northing (km)")
    cb = fig.colorbar(imc, ax=axes[0, :], ticks=range(C), shrink=0.9, pad=0.02)
    cb.ax.set_yticklabels([n if len(n) < 14 else "Marnes et Haut." for n in ROCK_NAMES], fontsize=7)
    fig.colorbar(imf, ax=axes[1, :], shrink=0.9, extend="max", pad=0.02)
    save(fig, "figure3")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
